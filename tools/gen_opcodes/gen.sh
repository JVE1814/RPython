#!/usr/bin/env bash
# Generates crates/compiler/src/wordcode/opcodes.rs from the public header
# spec/Include/opcode_ids.h (the ABI contract for opcode numbers, D24).
# Usage: tools/gen_opcodes/gen.sh
set -euo pipefail
root="$(cd "$(dirname "$0")/../.." && pwd)"
hdr="$root/spec/Include/opcode_ids.h"
out="$root/crates/compiler/src/wordcode/opcodes.rs"
{
  echo "// @generated by tools/gen_opcodes/gen.sh from spec/Include/opcode_ids.h; do not edit."
  echo "//! Opcode numbers (real opcodes 0..=255, pseudo-instructions >= 256)."
  echo
  awk '/^#define [A-Z_0-9]+ +[0-9]+$/ {
         name=$2; val=$3;
         printf "pub const %s: u16 = %s;\n", name, val;
         if (name == "HAVE_ARGUMENT" || name == "MIN_SPECIALIZED_OPCODE" || name == "MIN_INSTRUMENTED_OPCODE") next;
         names[n++] = name; vals[name] = val
       }
       END {
         printf "\n/// (name, number) for every opcode and pseudo-opcode, in header order.\n"
         printf "pub static ALL: [(&str, u16); %d] = [\n", n
         for (i = 0; i < n; i++) printf "    (\"%s\", %s),\n", names[i], vals[names[i]]
         printf "];\n"
       }' "$hdr"
} > "$out"
echo "wrote $out"
