//! Generate the charmap codec modules `Lib/encodings/<module>.py` from
//! `tools/gencodecs/data/<module>.map` ("HH UUUU" per defined byte; missing
//! bytes are undefined).
//!
//! Usage: cargo run --manifest-path tools/gencodecs/Cargo.toml [repo-root]

use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

fn escape(c: u32) -> String {
    match c {
        0x5C => "\\\\".to_string(),
        0x27 => "\\'".to_string(),
        0x20..=0x7E => (c as u8 as char).to_string(),
        0..=0xFF => format!("\\x{:02x}", c),
        0x100..=0xFFFF => format!("\\u{:04x}", c),
        _ => format!("\\U{:08x}", c),
    }
}

fn generate(module: &str, map: &str) -> String {
    let mut table = [0xFFFEu32; 256];
    for line in map.lines() {
        let mut it = line.split_whitespace();
        let (Some(b), Some(u)) = (it.next(), it.next()) else { continue };
        let b = u8::from_str_radix(b, 16).expect("bad byte");
        let u = u32::from_str_radix(u, 16).expect("bad code point");
        table[b as usize] = u;
    }
    let name = module.replace('_', "-");
    let mut s = String::new();
    let _ = writeln!(s, "\"\"\"Character mapping codec {name}.\n\nGenerated by tools/gencodecs from tools/gencodecs/data/{module}.map; do not edit.\n\"\"\"\n");
    s.push_str(
        "import codecs\n\n\
class Codec(codecs.Codec):\n\n    \
def encode(self, input, errors='strict'):\n        \
return codecs.charmap_encode(input, errors, encoding_table)\n\n    \
def decode(self, input, errors='strict'):\n        \
return codecs.charmap_decode(input, errors, decoding_table)\n\n\n\
class IncrementalEncoder(codecs.IncrementalEncoder):\n    \
def encode(self, input, final=False):\n        \
return codecs.charmap_encode(input, self.errors, encoding_table)[0]\n\n\n\
class IncrementalDecoder(codecs.IncrementalDecoder):\n    \
def decode(self, input, final=False):\n        \
return codecs.charmap_decode(input, self.errors, decoding_table)[0]\n\n\n\
class StreamWriter(Codec, codecs.StreamWriter):\n    pass\n\n\n\
class StreamReader(Codec, codecs.StreamReader):\n    pass\n\n\n\
def getregentry():\n    \
return codecs.CodecInfo(\n",
    );
    let _ = writeln!(s, "        name='{name}',");
    s.push_str(
        "        encode=Codec().encode,\n        \
decode=Codec().decode,\n        \
incrementalencoder=IncrementalEncoder,\n        \
incrementaldecoder=IncrementalDecoder,\n        \
streamreader=StreamReader,\n        \
streamwriter=StreamWriter,\n    )\n\n\n\
# Byte -> character; '\\ufffe' marks an undefined byte.\n\
decoding_table = (\n",
    );
    for row in 0..32 {
        s.push_str("    '");
        for col in 0..8 {
            s.push_str(&escape(table[row * 8 + col]));
        }
        let _ = writeln!(s, "'  # 0x{:02X}-0x{:02X}", row * 8, row * 8 + 7);
    }
    s.push_str(")\n\nencoding_table = codecs.charmap_build(decoding_table)\n");
    s
}

fn main() {
    let root = std::env::args().nth(1).map(PathBuf::from).unwrap_or_else(|| {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
    });
    let data = root.join("tools/gencodecs/data");
    let out = root.join("Lib/encodings");
    fs::create_dir_all(&out).unwrap();
    let mut names: Vec<_> = fs::read_dir(&data)
        .unwrap()
        .filter_map(|e| e.ok())
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|x| x == "map"))
        .collect();
    names.sort();
    for p in &names {
        let module = p.file_stem().unwrap().to_str().unwrap();
        let map = fs::read_to_string(p).unwrap();
        let py = generate(module, &map);
        fs::write(out.join(format!("{module}.py")), py).unwrap();
    }
    println!("generated {} codec modules in {}", names.len(), out.display());
}
