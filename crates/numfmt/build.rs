//! Generates the 128-bit power-of-ten table used by the Schubfach shortest
//! float-to-decimal algorithm (src/dtoa.rs).
//!
//! For k in [K_MIN, K_MAX]:  g(k) = floor(10^-k * 2^(125 - flog2pow10(-k))) + 1,
//! so that 2^125 < g(k) <= 2^126.

#[allow(dead_code)]
#[path = "src/bignum.rs"]
mod bignum;

use std::fmt::Write;

const K_MIN: i32 = -324;
const K_MAX: i32 = 292;

fn flog2pow10(e: i32) -> i32 {
    ((e as i64 * 913_124_641_741) >> 38) as i32
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src/bignum.rs");
    let mut out = String::new();
    writeln!(out, "// Generated by build.rs; do not edit.").unwrap();
    writeln!(out, "pub(crate) static G_TABLE: [u128; {}] = [", K_MAX - K_MIN + 1).unwrap();
    for k in K_MIN..=K_MAX {
        let n = -k; // power of ten
        let sh = 125 - flog2pow10(n);
        let mut b = bignum::Big::from_u64(1);
        if n >= 0 {
            b.mul_pow5(n as u32);
            // 10^n = 5^n 2^n
            let twos = n + sh;
            if twos >= 0 {
                b.shl(twos as u32);
            } else {
                b.shr_sticky((-twos) as u32);
            }
        } else {
            // 2^sh / 10^-n = 2^(sh+n) / 5^-n
            let twos = sh + n;
            assert!(twos >= 0);
            b.shl(twos as u32);
            b.div_pow5_sticky((-n) as u32);
        }
        b.add_small(1);
        let mut buf = [0u8; 64];
        let len = b.write_decimal(&mut buf);
        let s = std::str::from_utf8(&buf[..len]).unwrap();
        let v: u128 = s.parse().unwrap();
        assert!(v > (1u128 << 125) && v <= (1u128 << 126), "k={}", k);
        writeln!(out, "    0x{:032x},", v).unwrap();
    }
    writeln!(out, "];").unwrap();
    let dir = std::env::var("OUT_DIR").unwrap();
    std::fs::write(format!("{}/g_table.rs", dir), out).unwrap();
}
