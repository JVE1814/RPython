"""Create and inspect executable Python zip archives (.pyz files).

An application archive is a zip file with a ``__main__.py`` at its root,
optionally preceded by a ``#!interpreter`` line so that it can be run
directly on POSIX systems.
"""

import contextlib
import os
import pathlib
import shutil
import stat
import sys
import zipfile

__all__ = ['ZipAppError', 'create_archive', 'get_interpreter']

# Encoding of the interpreter path in the shebang line.
if sys.platform.startswith('win'):
    shebang_encoding = 'utf-8'
else:
    shebang_encoding = sys.getfilesystemencoding()

MAIN_TEMPLATE = """\
# Entry point generated by zipapp
import sys
import {module}
sys.exit({module}.{function}())
"""


class ZipAppError(ValueError):
    pass


def _is_file_object(obj):
    return hasattr(obj, 'read') or hasattr(obj, 'write')


@contextlib.contextmanager
def _maybe_open(archive, mode):
    """Open *archive* if it is a path; pass file objects through."""
    if isinstance(archive, (str, os.PathLike)):
        with open(archive, mode) as f:
            yield f
    else:
        yield archive


def _shebang(interpreter):
    return b'#!' + interpreter.encode(shebang_encoding) + b'\n'


def _copy_archive(archive, new_archive, interpreter=None):
    """Copy an application archive, replacing (or dropping) its shebang."""
    with _maybe_open(archive, 'rb') as src:
        head = src.read(2)
        if head == b'#!':
            src.readline()      # skip the old interpreter line
            head = b''
        with _maybe_open(new_archive, 'wb') as dst:
            if interpreter:
                dst.write(_shebang(interpreter))
            dst.write(head)
            shutil.copyfileobj(src, dst)

    if interpreter and isinstance(new_archive, (str, os.PathLike)):
        _make_executable(new_archive)


def _make_executable(path):
    mode = os.stat(path).st_mode
    os.chmod(path, mode | stat.S_IEXEC | stat.S_IXGRP | stat.S_IXOTH)


def _check_entry_point(main):
    module, sep, function = main.partition(':')
    valid = (
        sep == ':'
        and module
        and function
        and all(part.isidentifier() for part in module.split('.'))
        and all(part.isidentifier() for part in function.split('.'))
    )
    if not valid:
        raise ZipAppError("Invalid entry point: " + main)
    return module, function


def create_archive(source, target=None, interpreter=None, main=None,
                   filter=None, compressed=False):
    """Create an application archive from *source*.

    *source* is a directory (whose contents are archived) or an existing
    archive (path or file object) to copy with a new shebang line.
    *target* defaults to the source directory name with a .pyz suffix.
    *interpreter* is written as a ``#!`` line (the archive is then made
    executable); *main* ('pkg.module:function') generates ``__main__.py``.
    *filter*, given the path of each file relative to *source*, returns
    whether to include it.  *compressed* selects ZIP_DEFLATED.
    """
    if _is_file_object(source) or (
        isinstance(source, (str, os.PathLike)) and os.path.isfile(source)
    ):
        if main is not None:
            raise ZipAppError("Cannot change the main function when copying")
        _copy_archive(source, target, interpreter)
        return

    source = pathlib.Path(source)
    if not source.exists():
        raise ZipAppError("Source does not exist")
    has_main = (source / '__main__.py').is_file()
    if main and has_main:
        raise ZipAppError(
            "Cannot specify entry point if the source has __main__.py")
    if not (main or has_main):
        raise ZipAppError("Archive has no entry point")

    main_py = None
    if main:
        module, function = _check_entry_point(main)
        main_py = MAIN_TEMPLATE.format(module=module, function=function)

    if target is None:
        target = source.with_suffix('.pyz')
    elif not _is_file_object(target):
        target = pathlib.Path(target)

    # Decide on the members before the target file is (re)created.
    members = []
    target_resolved = None if _is_file_object(target) else target.resolve()
    for child in sorted(source.rglob('*')):
        relative = child.relative_to(source)
        if filter is not None and not filter(relative):
            continue
        if target_resolved is not None and child.resolve() == target_resolved:
            raise ZipAppError(
                f"The target archive {target} overwrites one of the source files.")
        members.append((child, relative))

    compression = zipfile.ZIP_DEFLATED if compressed else zipfile.ZIP_STORED
    with _maybe_open(target, 'wb') as fd:
        if interpreter:
            fd.write(_shebang(interpreter))
        with zipfile.ZipFile(fd, 'w', compression=compression) as z:
            for child, relative in members:
                z.write(child, relative.as_posix())
            if main_py is not None:
                z.writestr('__main__.py', main_py.encode('utf-8'))

    if interpreter and not _is_file_object(target):
        _make_executable(target)


def get_interpreter(archive):
    """Return the interpreter named in *archive*'s shebang line, or None."""
    with _maybe_open(archive, 'rb') as f:
        if f.read(2) == b'#!':
            return f.readline().strip().decode(shebang_encoding)
    return None


def main(args=None):
    """Command line interface: python -m zipapp SOURCE [options]."""
    import argparse

    parser = argparse.ArgumentParser()
    parser.add_argument('--output', '-o', default=None,
            help="The name of the output archive. "
                 "Required if SOURCE is an archive.")
    parser.add_argument('--python', '-p', default=None,
            help="The name of the Python interpreter to use "
                 "(default: no shebang line).")
    parser.add_argument('--main', '-m', default=None,
            help="The main function of the application "
                 "(default: use an existing __main__.py).")
    parser.add_argument('--compress', '-c', action='store_true',
            help="Compress files with the deflate method. "
                 "Files are stored uncompressed by default.")
    parser.add_argument('--info', default=False, action='store_true',
            help="Display the interpreter from the archive.")
    parser.add_argument('source',
            help="Source directory (or existing archive).")

    args = parser.parse_args(args)

    if args.info:
        if not os.path.isfile(args.source):
            raise SystemExit("Can only get info for an archive file")
        interpreter = get_interpreter(args.source)
        print(f"Interpreter: {interpreter or '<none>'}")
        sys.exit(0)

    if os.path.isfile(args.source):
        if args.output is None or (
            os.path.exists(args.output)
            and os.path.samefile(args.source, args.output)
        ):
            raise SystemExit("In-place editing of archives is not supported")
        if args.main:
            raise SystemExit("Cannot change the main function when copying")

    create_archive(args.source, args.output,
                   interpreter=args.python, main=args.main,
                   compressed=args.compress)


if __name__ == '__main__':
    main()
