def map_table_b3(code):
    """B.3: case folding used with no normalization."""
    r = _b3_table.get(ord(code))
    if r is not None:
        return r
    return code


def map_table_b2(a):
    """B.2: case folding used with NFKC."""
    al = map_table_b3(a)
    b = unicodedata.normalize("NFKC", al)
    bl = "".join([map_table_b3(ch) for ch in b])
    c = unicodedata.normalize("NFKC", bl)
    if b != c:
        return c
    else:
        return al


def in_table_c11(code):
    """C.1.1: ASCII space."""
    return code == " "


def in_table_c12(code):
    """C.1.2: non-ASCII space characters."""
    return unicodedata.category(code) == "Zs" and code != " "


def in_table_c11_c12(code):
    return unicodedata.category(code) == "Zs"


def in_table_c21(code):
    """C.2.1: ASCII control characters."""
    return ord(code) < 128 and unicodedata.category(code) == "Cc"


c22_specials = set([1757, 1807, 6158, 8204, 8205, 8232, 8233, 65279]
                   + list(range(8288, 8292)) + list(range(8298, 8304))
                   + list(range(65529, 65533)) + list(range(119155, 119163)))


def in_table_c22(code):
    """C.2.2: non-ASCII control characters."""
    c = ord(code)
    if c < 128:
        return False
    if unicodedata.category(code) == "Cc":
        return True
    return c in c22_specials


def in_table_c21_c22(code):
    return unicodedata.category(code) == "Cc" or \
           ord(code) in c22_specials


def in_table_c3(code):
    """C.3: private use."""
    return unicodedata.category(code) == "Co"


def in_table_c4(code):
    """C.4: non-character code points."""
    c = ord(code)
    if c < 0xFDD0:
        return False
    if c < 0xFDF0:
        return True
    return (ord(code) & 0xFFFF) in (0xFFFE, 0xFFFF)


def in_table_c5(code):
    """C.5: surrogate codes."""
    return unicodedata.category(code) == "Cs"


c6_set = set(range(65529, 65534))


def in_table_c6(code):
    """C.6: inappropriate for plain text."""
    return ord(code) in c6_set


