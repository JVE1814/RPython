"""Library that exposes the tables of RFC 3454 (stringprep).

Each table X is available as a predicate in_table_x(ch) or, for the
mapping tables B.2 and B.3, as map_table_x(ch).  Character properties come
from the Unicode 3.2.0 database (unicodedata.ucd_3_2_0), as RFC 3454
requires.
"""

from unicodedata import ucd_3_2_0 as unicodedata

assert unicodedata.unidata_version == '3.2.0'


def in_table_a1(code):
    """A.1: unassigned code points in Unicode 3.2."""
    if unicodedata.category(code) != 'Cn':
        return False
    c = ord(code)
    if 0xFDD0 <= c < 0xFDF0:
        return False
    return (c & 0xFFFF) not in (0xFFFE, 0xFFFF)


b1_set = set([173, 847, 6150, 6155, 6156, 6157, 8203, 8204, 8205, 8288, 65279]
             + list(range(65024, 65040)))


def in_table_b1(code):
    """B.1: commonly mapped to nothing."""
    return ord(code) in b1_set


def _parse_b3(data):
    table = {}
    for item in data.split(';'):
        if item:
            src, dst = item.split(':')
            table[int(src, 16)] = ''.join(chr(int(x, 16)) for x in dst.split())
    return table


